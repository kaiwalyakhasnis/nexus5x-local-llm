#!/usr/bin/env python3
"""Bake logos into a C header for llm-ui: each PNG is centred on a white
rounded card, composited over the screen background and stored as RGBX rows
that gr_blit can copy straight to the framebuffer (needs python3-pil).
Usage: logo2h.py out.h name=file.png ..."""
import sys
from PIL import Image, ImageDraw

CARD, LOGO, RADIUS = 360, 300, 48
BG = (10, 12, 16)  # keep in sync with kBg in main.cpp

out = [f"// generated by logo2h.py from {' '.join(sys.argv[2:])}\n",
       f"static const int kLogoSize = {CARD};\n"]
for arg in sys.argv[2:]:
    name, path = arg.split("=", 1)
    img = Image.new("RGBA", (CARD, CARD), BG + (255,))
    ImageDraw.Draw(img).rounded_rectangle((0, 0, CARD - 1, CARD - 1), RADIUS, fill=(255, 255, 255, 255))
    logo = Image.open(path).convert("RGBA").resize((LOGO, LOGO), Image.LANCZOS)
    img.alpha_composite(logo, ((CARD - LOGO) // 2, (CARD - LOGO) // 2))
    data = img.convert("RGB").tobytes()
    px = bytearray()
    for i in range(0, len(data), 3):
        px += data[i:i + 3] + b"\0"
    out.append(f"static const unsigned char logo_{name}[] = {{\n")
    for i in range(0, len(px), 32):
        out.append(",".join(map(str, px[i:i + 32])) + ",\n")
    out.append("};\n")
open(sys.argv[1], "w").write("".join(out))
