// The phone's address on the USB network (fixed by llm-usb.sh, read back in
// case that changes).
static std::string phone_ip() {
  int s = socket(AF_INET, SOCK_DGRAM, 0);
  if (s < 0) return "172.16.42.1";
  ifreq r = {};
  strncpy(r.ifr_name, kIface, IFNAMSIZ - 1);
  std::string ip = "172.16.42.1";
  if (ioctl(s, SIOCGIFADDR, &r) == 0) ip = inet_ntoa(((sockaddr_in*)&r.ifr_addr)->sin_addr);
  close(s);
  return ip;
}

// HTTP status of GET /health: 200 ready, 503 still loading, 0 not running.
static int health() {
  int s = socket(AF_INET, SOCK_STREAM, 0);
  if (s < 0) return 0;
  sockaddr_in a = {};
  a.sin_family = AF_INET;
  a.sin_port = htons(kPort);
  a.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
  timeval tv = {0, 300000};
  setsockopt(s, SOL_SOCKET, SO_SNDTIMEO, &tv, sizeof(tv));
  int code = 0;
  const char req[] = "GET /health HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n";
  if (connect(s, (sockaddr*)&a, sizeof(a)) == 0 && send(s, req, sizeof(req) - 1, MSG_NOSIGNAL) > 0) {
    pollfd p = {s, POLLIN, 0};
    char buf[64] = {};
    if (poll(&p, 1, 500) == 1 && recv(s, buf, sizeof(buf) - 1, 0) > 12) code = atoi(buf + 9);  // "HTTP/1.1 200"
  }
  close(s);
  return code;
}

struct Screen {
  std::string model;   // empty: none yet
  std::string status;  // one line
  int color;           // 0 grey, 1 yellow, 2 green, 3 red
  std::string hint;    // optional second line under the status
  std::string url;
  int battery = -1;    // percent, -1 unknown
  bool charging = false;
  int cpu = -1;        // all cores busy, percent over the last second
  int mem_used = -1;   // RAM in use, percent (the model in /tmp counts as used)
  VoiceView voice;
  bool operator!=(const Screen& o) const {
    return model != o.model || status != o.status || color != o.color || hint != o.hint || url != o.url ||
           battery != o.battery || charging != o.charging || cpu != o.cpu || mem_used != o.mem_used ||
           voice.available != o.voice.available ||
           voice.phase != o.voice.phase || voice.question != o.voice.question || voice.answer != o.voice.answer ||
           voice.sound != o.voice.sound || voice.turn != o.voice.turn || voice.ctx_used != o.voice.ctx_used ||
           voice.ctx_max != o.voice.ctx_max || voice.new_after_full != o.voice.new_after_full;
  }
};

// CPU busy percent across all cores since the previous call (/proc/stat),
// sampled at most once a second; -1 until there are two samples.
static int cpu_percent() {
  static unsigned long long prev_busy = 0, prev_total = 0;
  static long long prev_ms = 0;
  static int last = -1;
  timespec t;
  clock_gettime(CLOCK_MONOTONIC, &t);
  long long ms = t.tv_sec * 1000LL + t.tv_nsec / 1000000;
  if (prev_ms && ms - prev_ms < 900) return last;
  FILE* f = fopen("/proc/stat", "r");
  if (!f) return last;
  unsigned long long v[8] = {};
  int n = fscanf(f, "cpu %llu %llu %llu %llu %llu %llu %llu %llu", &v[0], &v[1], &v[2], &v[3], &v[4], &v[5],
                 &v[6], &v[7]);
  fclose(f);
  if (n < 4) return last;
  unsigned long long idle = v[3] + v[4], total = 0;  // idle + iowait
  for (auto x : v) total += x;
  if (prev_total && total > prev_total)
    last = int(100 * ((total - idle) - prev_busy) / (total - prev_total));
  prev_busy = total - idle;
  prev_total = total;
  prev_ms = ms;
  return last;
}

// RAM in use, percent. This 3.10 kernel has no MemAvailable: free + buffers +
// page cache count as available, except tmpfs (Shmem), where the model lives.
static int mem_used_percent() {
  FILE* f = fopen("/proc/meminfo", "r");
  if (!f) return -1;
  long total = 0, free_ = 0, buffers = 0, cached = 0, shmem = 0, v;
  char key[64];
  while (fscanf(f, "%63s %ld kB", key, &v) == 2) {
    if (!strcmp(key, "MemTotal:")) total = v;
    else if (!strcmp(key, "MemFree:")) free_ = v;
    else if (!strcmp(key, "Buffers:")) buffers = v;
    else if (!strcmp(key, "Cached:")) cached = v;
    else if (!strcmp(key, "Shmem:")) shmem = v;
  }
  fclose(f);
  if (!total) return -1;
  long avail = free_ + buffers + cached - shmem;
  return int(100 * (total - avail) / total);
}

// llama serve is running (llm-serve writes its pid).
static bool server_running() {
  int pid = atoi(read_file("/run/llama-server.pid").c_str());
  return pid > 0 && kill(pid, 0) == 0;
}

static Screen current() {
  Screen s;
  s.url = "http://" + phone_ip() + ":" + std::to_string(kPort);
  s.model = read_file("/tmp/model.name");
  std::string cap = read_file("/sys/class/power_supply/battery/capacity");
  if (!cap.empty()) s.battery = atoi(cap.c_str());
  s.charging = read_file("/sys/class/power_supply/battery/status") == "Charging";
  s.cpu = cpu_percent();
  s.mem_used = mem_used_percent();
  s.voice = voice_view();
  long long part = file_size("/tmp/model.part");  // llmd's upload in progress
  int code = health();
  if (part > 0) {
    s.status = "receiving... " + std::to_string(part >> 20) + " MB";
    s.color = 1;
    if (s.model.empty()) s.model = "new model";
  } else if (code == 200) {
    s.status = "ready";
    s.color = 2;
  } else if (code == 503 || (code == 0 && file_size("/tmp/model.gguf") > 0 && server_running())) {
    s.status = "loading model...";
    s.color = 1;
  } else if (file_size("/tmp/model.gguf") > 0) {
    s.status = "model failed to load";
    s.hint = "too big for the RAM, or not supported";
    s.color = 3;
  } else {
    s.status = "waiting for a model";
    s.hint = "load one from the Nexus 5X LLM app on the PC";
    s.color = 0;
  }
  return s;
}

