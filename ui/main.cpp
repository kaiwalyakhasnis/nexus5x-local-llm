// llm-ui: the phone's screen shows what is loaded and where to chat with it.
//
// Chatting happens in llama.cpp's web UI on the PC (http://<phone>:8080 over
// USB networking); this screen only shows the model's logo and name, the
// server state and that URL. It redraws when something changes. POWER turns
// the screen off and on.
#include <arpa/inet.h>
#include <fcntl.h>
#include <linux/input.h>
#include <net/if.h>
#include <netinet/in.h>
#include <poll.h>
#include <signal.h>
#include <sys/ioctl.h>
#include <sys/socket.h>
#include <sys/stat.h>
#include <sys/time.h>
#include <unistd.h>

#include <algorithm>
#include <cstring>
#include <string>
#include <vector>

#include "minui/minui.h"
#include "logos.h"  // generated by logo2h.py: kLogoSize, logo_<name> per ui/assets/<name>.png

static const unsigned char kBg[3] = {10, 12, 16};  // keep in sync with BG in logo2h.py
static const char* kIface = "rndis0";              // USB network, see etc/llm-usb.sh
static const int kPort = 8080;

static int W = 1080, H = 1920;
static const GRFont* font;
static int CW = 10, CH = 18;  // font cell before scaling
static bool screen_on = true;

static std::string read_file(const char* path) {
  char buf[256];
  int fd = open(path, O_RDONLY);
  if (fd < 0) return "";
  int n = read(fd, buf, sizeof(buf) - 1);
  close(fd);
  if (n <= 0) return "";
  buf[n] = 0;
  std::string s(buf);
  while (!s.empty() && (s.back() == '\n' || s.back() == ' ')) s.pop_back();
  return s;
}

static void write_file(const char* path, const char* s) {
  int fd = open(path, O_WRONLY);
  if (fd < 0) return;
  (void)!write(fd, s, strlen(s));
  close(fd);
}

static long long file_size(const char* path) {
  struct stat st;
  return stat(path, &st) == 0 ? st.st_size : -1;
}

// ---------------------------------------------------------------- state

// The phone's address on the USB network (fixed by llm-usb.sh, read back in
// case that changes).
static std::string phone_ip() {
  int s = socket(AF_INET, SOCK_DGRAM, 0);
  if (s < 0) return "172.16.42.1";
  ifreq r = {};
  strncpy(r.ifr_name, kIface, IFNAMSIZ - 1);
  std::string ip = "172.16.42.1";
  if (ioctl(s, SIOCGIFADDR, &r) == 0) ip = inet_ntoa(((sockaddr_in*)&r.ifr_addr)->sin_addr);
  close(s);
  return ip;
}

// HTTP status of GET /health: 200 ready, 503 still loading, 0 not running.
static int health() {
  int s = socket(AF_INET, SOCK_STREAM, 0);
  if (s < 0) return 0;
  sockaddr_in a = {};
  a.sin_family = AF_INET;
  a.sin_port = htons(kPort);
  a.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
  timeval tv = {0, 300000};
  setsockopt(s, SOL_SOCKET, SO_SNDTIMEO, &tv, sizeof(tv));
  int code = 0;
  const char req[] = "GET /health HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n";
  if (connect(s, (sockaddr*)&a, sizeof(a)) == 0 && send(s, req, sizeof(req) - 1, MSG_NOSIGNAL) > 0) {
    pollfd p = {s, POLLIN, 0};
    char buf[64] = {};
    if (poll(&p, 1, 500) == 1 && recv(s, buf, sizeof(buf) - 1, 0) > 12) code = atoi(buf + 9);  // "HTTP/1.1 200"
  }
  close(s);
  return code;
}

struct Screen {
  std::string model;   // empty: none yet
  std::string status;  // one line
  int color;           // 0 grey, 1 yellow, 2 green, 3 red
  std::string hint;    // optional second line under the status
  std::string url;
  bool operator!=(const Screen& o) const {
    return model != o.model || status != o.status || color != o.color || hint != o.hint || url != o.url;
  }
};

// llama serve is running (llm-serve writes its pid).
static bool server_running() {
  int pid = atoi(read_file("/run/llama-server.pid").c_str());
  return pid > 0 && kill(pid, 0) == 0;
}

static Screen current() {
  Screen s;
  s.url = "http://" + phone_ip() + ":" + std::to_string(kPort);
  s.model = read_file("/tmp/model.name");
  long long part = file_size("/tmp/model.part");  // llmd's upload in progress
  int code = health();
  if (part > 0) {
    s.status = "receiving model... " + std::to_string(part >> 20) + " MB";
    s.color = 1;
    if (s.model.empty()) s.model = "new model";
  } else if (code == 200) {
    s.status = "ready";
    s.color = 2;
  } else if (code == 503 || (code == 0 && file_size("/tmp/model.gguf") > 0 && server_running())) {
    s.status = "loading model...";
    s.color = 1;
  } else if (file_size("/tmp/model.gguf") > 0) {
    s.status = "model failed to load";
    s.hint = "too big for the RAM, or not supported";
    s.color = 3;
  } else {
    s.status = "waiting for a model";
    s.hint = "load one from the Nexus 5X LLM app on the PC";
    s.color = 0;
  }
  return s;
}

// ---------------------------------------------------------------- drawing

// Largest text scale (up to max) at which s fits the screen width.
static int fit(const std::string& s, int max) {
  int scale = max;
  while (scale > 2 && int(s.size()) * CW * scale > W - 2 * 48) --scale;
  return scale;
}

static void text_centered(int y, const std::string& s, int scale) {
  gr_text_scaled(font, (W - int(s.size()) * CW * scale) / 2, y, s.c_str(), scale);
}

// The model family's logo, from its name ("Google Gemma 3 1b It", ...);
// Ollama's llama for anything else.
static const unsigned char* logo_for(const std::string& model) {
  std::string m = model;
  std::transform(m.begin(), m.end(), m.begin(), ::tolower);
  static const struct { const char* key; const unsigned char* logo; } families[] = {
      {"deepseek", logo_deepseek},  // before qwen: "DeepSeek R1 Distill Qwen"
      {"gemma", logo_gemma},
      {"qwen", logo_qwen},
      {"smollm", logo_huggingface},
      {"llama", logo_meta},
  };
  for (const auto& f : families)
    if (m.find(f.key) != std::string::npos) return f.logo;
  return logo_ollama;
}

static void draw_logo(const std::string& model, int y) {
  GRSurface logo = {kLogoSize, kLogoSize, kLogoSize * 4, 4, const_cast<unsigned char*>(logo_for(model))};
  gr_blit(&logo, 0, 0, kLogoSize, kLogoSize, (W - kLogoSize) / 2, y);
}

static void draw(const Screen& s) {
  gr_color(kBg[0], kBg[1], kBg[2], 255);
  gr_clear();

  int y = 300;
  draw_logo(s.model, y);
  y += kLogoSize + 80;

  std::string name = s.model.empty() ? "no model" : s.model;
  gr_color(240, 240, 240, 255);
  int scale = fit(name, 5);
  text_centered(y, name, scale);
  y += CH * scale + 40;

  if (s.color == 2) gr_color(110, 210, 120, 255);
  else if (s.color == 1) gr_color(235, 200, 90, 255);
  else if (s.color == 3) gr_color(240, 110, 100, 255);
  else gr_color(150, 150, 150, 255);
  text_centered(y, s.status, fit(s.status, 3));
  y += CH * 3 + 20;
  if (!s.hint.empty()) {
    gr_color(150, 150, 150, 255);
    text_centered(y, s.hint, fit(s.hint, 2));
  }

  y = 1300;
  gr_color(60, 66, 80, 255);
  gr_fill(120, y, W - 120, y + 3);
  y += 80;
  gr_color(170, 170, 170, 255);
  text_centered(y, "chat in a browser on the PC:", 3);
  y += CH * 3 + 40;
  gr_color(120, 185, 255, 255);
  text_centered(y, s.url, fit(s.url, 5));

  gr_flip();
}

// ---------------------------------------------------------------- input

static void set_screen(bool on) {
  screen_on = on;
  gr_fb_blank(!on);
  write_file("/sys/class/leds/lcd-backlight/brightness", on ? "80" : "0");  // of 255
}

static bool redraw = true;

static int on_input(int fd, uint32_t epevents) {
  input_event ev;
  if (ev_get_input(fd, epevents, &ev) != 0) return 0;
  if (ev.type == EV_KEY && ev.value == 1 && ev.code == KEY_POWER) {
    set_screen(!screen_on);
    redraw = true;
  }
  return 0;
}

// ---------------------------------------------------------------- main

static void ui_init() {
  W = gr_fb_width();
  H = gr_fb_height();
  font = gr_sys_font();
  gr_font_size(font, &CW, &CH);
}

int main() {
  if (gr_init() != 0) {
    fprintf(stderr, "llm-ui: no framebuffer\n");
    return 1;
  }
  ui_init();
  if (ev_init(on_input, true) != 0) fprintf(stderr, "llm-ui: no input devices\n");
  set_screen(true);
  Screen shown;
  while (true) {
    if (ev_wait(1000) == 0) ev_dispatch();
    Screen s = current();
    if (screen_on && (redraw || s != shown)) {
      draw(s);
      shown = s;
      redraw = false;
    }
  }
}
