static const unsigned char kBg[3] = {10, 12, 16};  // keep in sync with BG in logo2h.py
static const char* kIface = "rndis0";              // USB network, see etc/llm-usb.sh
static const int kPort = 8080;

static int W = 1080, H = 1920;
static const GRFont* font;
static int CW = 10, CH = 18;  // font cell before scaling
static bool screen_on = true;

static std::string read_file(const char* path) {
  char buf[256];
  int fd = open(path, O_RDONLY);
  if (fd < 0) return "";
  int n = read(fd, buf, sizeof(buf) - 1);
  close(fd);
  if (n <= 0) return "";
  buf[n] = 0;
  std::string s(buf);
  while (!s.empty() && (s.back() == '\n' || s.back() == ' ')) s.pop_back();
  return s;
}

static void write_file(const char* path, const char* s) {
  int fd = open(path, O_WRONLY);
  if (fd < 0) return;
  (void)!write(fd, s, strlen(s));
  close(fd);
}

static long long file_size(const char* path) {
  struct stat st;
  return stat(path, &st) == 0 ? st.st_size : -1;
}

