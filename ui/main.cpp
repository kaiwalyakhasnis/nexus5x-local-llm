// Largest text scale (up to max) at which s fits the screen width.
static int fit(const std::string& s, int max) {
  int scale = max;
  while (scale > 2 && int(s.size()) * CW * scale > W - 2 * 48) --scale;
  return scale;
}

static void text_centered(int y, const std::string& s, int scale) {
  gr_text_scaled(font, (W - int(s.size()) * CW * scale) / 2, y, s.c_str(), scale);
}

// UTF-8 -> what the 10x18 ASCII font can show.
static std::string ascii(const std::string& s) {
  std::string o;
  for (size_t i = 0; i < s.size();) {
    unsigned char c = s[i];
    unsigned cp;
    int n;
    if (c < 0x80) { cp = c; n = 1; }
    else if ((c >> 5) == 6) { cp = c & 0x1F; n = 2; }
    else if ((c >> 4) == 14) { cp = c & 0x0F; n = 3; }
    else if ((c >> 3) == 30) { cp = c & 0x07; n = 4; }
    else { cp = '?'; n = 1; }
    for (int k = 1; k < n && i + k < s.size(); ++k) cp = (cp << 6) | (s[i + k] & 0x3F);
    i += n;
    if (cp == '\n' || (cp >= ' ' && cp <= '~')) o += char(cp);
    else if (cp == 0x2018 || cp == 0x2019) o += '\'';
    else if (cp == 0x201C || cp == 0x201D) o += '"';
    else if (cp == 0x2013 || cp == 0x2014) o += '-';
    else if (cp == 0x2026) o += "...";
  }
  return o;
}

// Greedy word wrap into lines of at most cols characters.
static std::vector<std::string> wrap(const std::string& s, int cols) {
  std::vector<std::string> out;
  std::string line, word;
  auto flush_word = [&] {
    while ((int)word.size() > cols) { out.push_back(word.substr(0, cols)); word.erase(0, cols); }
    if (line.empty()) line = word;
    else if ((int)(line.size() + 1 + word.size()) <= cols) line += " " + word;
    else { out.push_back(line); line = word; }
    word.clear();
  };
  for (char c : s) {
    if (c == ' ' || c == '\n') {
      if (!word.empty()) flush_word();
      if (c == '\n' && !line.empty()) { out.push_back(line); line.clear(); }
    } else {
      word += c;
    }
  }
  if (!word.empty()) flush_word();
  if (!line.empty()) out.push_back(line);
  return out;
}

// Question and answer of the last voice exchange, between y0 and y1.
static void draw_voice(const VoiceView& v, int y0, int y1) {
  const int x = 60, cols = (W - 2 * x) / (CW * 3), lh = CH * 3 + 10;
  int y = y0;
  if (!v.available) {
    gr_color(110, 110, 110, 255);
    text_centered(y, "voice: send the voice pack from the PC app", 2);
    return;
  }
  // bottom lines, small: the sound switch, and where the conversation is
  gr_color(v.sound ? 120 : 110, v.sound ? 200 : 110, v.sound ? 130 : 110, 255);
  text_centered(y1 - CH * 2, v.sound ? "sound on - VOLUME UP mutes" : "sound off - VOLUME UP turns it on", 2);
  y1 -= CH * 2 + 16;
  if (v.turn > 0) {
    auto k = [](int n) {  // context sizes count in 1024s: 32768 = 32K
      char b[16];
      if (n < 1000) snprintf(b, sizeof(b), "%d", n);
      else if (n < 10240) snprintf(b, sizeof(b), "%.1fK", n / 1024.0);
      else snprintf(b, sizeof(b), "%dK", (n + 512) / 1024);
      return std::string(b);
    };
    std::string t = v.new_after_full ? "context was full: new conversation"
                                     : "question " + std::to_string(v.turn) + " - context " + k(v.ctx_used) +
                                           " of " + k(v.ctx_max) + " tokens";
    gr_color(110, 110, 110, 255);
    text_centered(y1 - CH * 2, t, 2);
    y1 -= CH * 2 + 20;
  }
  if (!v.phase.empty()) {
    gr_color(235, 200, 90, 255);
    text_centered(y, v.phase, 3);
  } else if (v.question.empty()) {
    gr_color(150, 150, 150, 255);
    text_centered(y, "hold VOLUME DOWN, speak, let go", 3);
  }
  y += lh + 20;
  if (!v.question.empty()) {
    gr_color(120, 185, 255, 255);
    for (const auto& l : wrap(ascii(v.question), cols)) {
      if (y + lh > y1) return;
      gr_text_scaled(font, x, y, l.c_str(), 3);
      y += lh;
    }
    y += 16;
  }
  auto lines = wrap(ascii(v.answer), cols);
  int fits = std::max(0, (y1 - y) / lh);
  size_t first = lines.size() > (size_t)fits ? lines.size() - fits : 0;  // newest lines win
  gr_color(235, 235, 235, 255);
  for (size_t i = first; i < lines.size(); ++i, y += lh) gr_text_scaled(font, x, y, lines[i].c_str(), 3);
}

// The model family's logo, from its name ("Google Gemma 3 1b It", ...);
// Ollama's llama for anything else.
static const unsigned char* logo_for(const std::string& model) {
  std::string m = model;
  std::transform(m.begin(), m.end(), m.begin(), ::tolower);
  static const struct { const char* key; const unsigned char* logo; } families[] = {
      {"deepseek", logo_deepseek},  // before qwen: "DeepSeek R1 Distill Qwen"
      {"gemma", logo_gemma},
      {"qwen", logo_qwen},
      {"smollm", logo_huggingface},
      {"llama", logo_meta},
  };
  for (const auto& f : families)
    if (m.find(f.key) != std::string::npos) return f.logo;
  return logo_ollama;
}

static void draw_logo(const std::string& model, int y) {
  GRSurface logo = {kLogoSize, kLogoSize, kLogoSize * 4, 4, const_cast<unsigned char*>(logo_for(model))};
  gr_blit(&logo, 0, 0, kLogoSize, kLogoSize, (W - kLogoSize) / 2, y);
}

static void draw(const Screen& s) {
  gr_color(kBg[0], kBg[1], kBg[2], 255);
  gr_clear();

  // top-right corner, small: battery, then CPU and RAM (updated every second)
  int ty = 40;
  auto corner = [&](const std::string& t, bool alert) {
    if (alert) gr_color(240, 110, 100, 255);
    else gr_color(150, 150, 150, 255);
    gr_text_scaled(font, W - 40 - int(t.size()) * CW * 2, ty, t.c_str(), 2);
    ty += CH * 2 + 6;
  };
  if (s.battery >= 0)
    corner((s.charging ? "charging " : "") + std::to_string(s.battery) + "%", s.battery < 15 && !s.charging);
  if (s.cpu >= 0) corner("CPU " + std::to_string(s.cpu) + "%", false);
  if (s.mem_used >= 0) {
    corner("RAM used " + std::to_string(s.mem_used) + "%", false);
    corner("RAM free " + std::to_string(100 - s.mem_used) + "%", s.mem_used >= 90);
  }

  int y = 140;
  draw_logo(s.model, y);
  y += kLogoSize + 50;

  std::string name = s.model.empty() ? "no model" : s.model;
  gr_color(240, 240, 240, 255);
  int scale = fit(name, 5);
  text_centered(y, name, scale);
  y += CH * scale + 40;

  if (s.color == 2) gr_color(110, 210, 120, 255);
  else if (s.color == 1) gr_color(235, 200, 90, 255);
  else if (s.color == 3) gr_color(240, 110, 100, 255);
  else gr_color(150, 150, 150, 255);
  text_centered(y, s.status, fit(s.status, 3));
  y += CH * 3 + 20;
  if (!s.hint.empty()) {
    gr_color(150, 150, 150, 255);
    text_centered(y, s.hint, fit(s.hint, 2));
  }

  draw_voice(s.voice, 800, 1640);

  y = 1680;
  gr_color(60, 66, 80, 255);
  gr_fill(120, y, W - 120, y + 3);
  y += 40;
  gr_color(170, 170, 170, 255);
  text_centered(y, "chat in a browser on the PC:", 2);
  y += CH * 2 + 20;
  gr_color(120, 185, 255, 255);
  text_centered(y, s.url, fit(s.url, 4));

  gr_flip();
}

// ---------------------------------------------------------------- input

static void set_screen(bool on) {
  screen_on = on;
  gr_fb_blank(!on);
  write_file("/sys/class/leds/lcd-backlight/brightness", on ? "80" : "0");  // of 255
}

static bool redraw = true;

static int on_input(int fd, uint32_t epevents) {
  input_event ev;
  if (ev_get_input(fd, epevents, &ev) != 0) return 0;
  if (ev.type == EV_KEY && ev.value == 1 && ev.code == KEY_POWER) {
    set_screen(!screen_on);
    redraw = true;
  } else if (ev.type == EV_KEY && ev.code == KEY_VOLUMEDOWN && ev.value != 2) {  // push to talk
    if (ev.value == 1) {
      if (!screen_on) set_screen(true);
      voice_press();
    } else {
      voice_release();
    }
  } else if (ev.type == EV_KEY && ev.value == 1 && ev.code == KEY_VOLUMEUP) {  // sound on/off
    if (!screen_on) set_screen(true);
    voice_set_sound(!voice_view().sound);
    redraw = true;
  }
  return 0;
}

// ---------------------------------------------------------------- main

static void ui_init() {
  W = gr_fb_width();
  H = gr_fb_height();
  font = gr_sys_font();
  gr_font_size(font, &CW, &CH);
}

int main() {
  if (gr_init() != 0) {
    fprintf(stderr, "llm-ui: no framebuffer\n");
    return 1;
  }
  ui_init();
  if (ev_init(on_input, true) != 0) fprintf(stderr, "llm-ui: no input devices\n");
  set_screen(true);
  voice_init();
  Screen shown;
  std::string voice_json;
  while (true) {
    if (ev_wait(shown.voice.busy ? 150 : 1000) == 0) ev_dispatch();
    // test hook: "down"/"up" in /tmp/ptt acts as pressing/releasing VOLUME DOWN,
    // "sound on"/"sound off" sets what VOLUME UP toggles
    std::string ptt = read_file("/tmp/ptt");
    if (!ptt.empty()) {
      unlink("/tmp/ptt");
      if (ptt == "down") voice_press();
      else if (ptt == "up") voice_release();
      else if (ptt == "sound on" || ptt == "sound off") voice_set_sound(ptt == "sound on");
    }
    Screen s = current();
    // for the PC app (busybox httpd serves /tmp/www on :8081)
    std::string vj = std::string("{\"ready\":") + (s.voice.available ? "true" : "false") + ",\"busy\":" +
                     (s.voice.busy ? "true" : "false") + ",\"sound\":" + (s.voice.sound ? "true" : "false") + "}\n";
    if (vj != voice_json) {
      int fd = open("/tmp/www/voice.json", O_WRONLY | O_CREAT | O_TRUNC, 0644);
      if (fd >= 0) { (void)!write(fd, vj.data(), vj.size()); close(fd); voice_json = vj; }
    }
    if (screen_on && (redraw || s != shown)) {
      draw(s);
      shown = s;
      redraw = false;
    }
  }
}
