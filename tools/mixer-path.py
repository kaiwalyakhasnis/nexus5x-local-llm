#!/usr/bin/env python3
"""Turn routes from Android's mixer_paths.xml into tinymix commands.

Android's audio HAL sets the mixer defaults (the <ctl>s directly under
<mixer>) once, then applies a <path> to start a route and resets its controls
to the defaults to end it. Paths can include other paths. This prints the
same steps as a shell script for the phone:
  mixer-path.py mixer_paths.xml --defaults                  > mixer-defaults.sh
  mixer-path.py mixer_paths.xml deep-buffer-playback speaker > route-speaker.sh
  mixer-path.py mixer_paths.xml --reset speaker              > route-speaker-off.sh
  --skip NAME (repeatable) leaves out one control, e.g. the mic's sidetone IIR
"""
import shlex, sys
import xml.etree.ElementTree as ET

args = sys.argv[1:]
skip = set()
while "--skip" in args:
    i = args.index("--skip")
    skip.add(args[i + 1])
    del args[i:i + 2]
root = ET.parse(args.pop(0)).getroot()
defaults = [(c.get("name"), c.get("value"), c.get("id")) for c in root.findall("ctl")]
default_of = {n: v for n, v, _ in defaults}
paths = {}
for p in root.findall("path"):
    paths.setdefault(p.get("name"), p)  # the HAL uses the first of duplicated names


def expand(name):
    out = []
    for e in paths[name]:
        if e.tag == "path":
            out += expand(e.get("name"))
        elif e.tag == "ctl":
            if e.get("name") not in skip:
                out.append((e.get("name"), e.get("value"), e.get("id")))
    return out


def cmd(name, value, idx):
    if idx is not None:  # one element of an array control (voice calls only): skipped
        return f"# skipped: {name} [{idx}] = {value}"
    return f"tinymix set {shlex.quote(name)} {shlex.quote(value)}"


print("#!/bin/sh\n# generated by tools/mixer-path.py from mixer_paths.xml:", " ".join(args),
      *[f"(without {n})" for n in sorted(skip)])
if args[0] == "--defaults":
    lines = [cmd(*c) for c in defaults]
elif args[0] == "--reset":
    lines = [cmd(n, default_of[n], i) for a in args[1:] for n, _, i in reversed(expand(a)) if n in default_of]
else:
    lines = [cmd(*c) for a in args for c in expand(a)]
print("\n".join(lines))
